import i18n from "i18next";
import { initReactI18next } from "react-i18next";
import en from "./locales/en.json";
import hi from "./locales/hi.json";
import ar from "./locales/ar.json";

// Languages the POS UI ships a catalog for. `code` matches Frappe's own
// Language doctype names (User.language), so a cashier's configured Frappe
// language maps straight onto one of these. `dir: "rtl"` flips the whole
// layout (store/languageStore.js sets <html dir>, theme/bootstrapDirection.js
// swaps in Bootstrap's RTL build; our own CSS uses logical properties).
export const LANGUAGES = [
	{ code: "en", label: "English", dir: "ltr" },
	{ code: "hi", label: "हिन्दी", dir: "ltr" },
	{ code: "ar", label: "العربية", dir: "rtl" },
];

export const languageDir = (code) => LANGUAGES.find((l) => l.code === code)?.dir || "ltr";

// Keys are the English source strings themselves (Frappe's own `__("...")`
// convention), so a string missing from a catalog falls back to readable
// English instead of a dotted key. Catalogs are regenerated by
// `yarn i18n:extract` (scripts/i18n-extract.mjs), which scans every t() call
// with a literal string argument.
i18n.use(initReactI18next).init({
	// "translation" = UI strings (catalogs above); "data" = record values
	// (item names, payment modes, ...) loaded at runtime from the server's
	// Translation records — see i18n/dataTranslations.js and tData below.
	resources: {
		en: { translation: en, data: {} },
		hi: { translation: hi, data: {} },
		ar: { translation: ar, data: {} },
	},
	ns: ["translation", "data"],
	defaultNS: "translation",
	lng: "en",
	fallbackLng: "en",
	keySeparator: false,
	nsSeparator: false,
	returnEmptyString: false,
	// No promotional console banner on every page load.
	showSupportNotice: false,
	// React already escapes rendered text.
	interpolation: { escapeValue: false },
	// Re-render useTranslation() consumers when data translations arrive
	// after the first paint (addResourceBundle).
	react: { bindI18nStore: "added" },
});

// Marks a string for extraction without translating it — for module-level
// constants (nav items, table columns, status options) evaluated once at
// import, before/regardless of the active language. Whatever renders them
// translates at render time with t(key): ListTable/ChildTable column labels,
// FilterChips labels and Sidebar items already do.
export const _t = (key) => key;

// t() for a prop that may be a _t key or already-rendered content — only
// plain strings are looked up; elements/numbers/null pass through unchanged.
export const tLabel = (t, label) => (typeof label === "string" && label ? t(label) : label);

// A record value as stored in ERPNext (item name, mode of payment, item
// group, attribute value...) in the current language, when a Translation
// record exists for it — otherwise the value itself. Never use t() for these:
// they aren't catalog keys and the extractor must not harvest them.
export const tData = (value) =>
	typeof value === "string" && value ? i18n.t(value, { ns: "data", defaultValue: value }) : value;

export default i18n;
